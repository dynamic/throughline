#!/bin/sh
# Generated redaction sweep (issue #174).
#
# Hand-picked rows found each instance of the rule-consumes-keyword defect one at a
# time (#116, #121, #123, #173). This builds a corpus as prefix x keyword x separator
# x value x suffix, plus two- and three-keyword chains, runs every input through an
# engine's `redact`, and counts the inputs whose seeded marker survives.
#
# It is a ratchet, not a zero gate: inputs that leak on every engine today are known
# and tracked (#220), so the script fails when an engine leaks MORE than its pinned
# baseline and asks for the baseline to be lowered when it leaks less.
#
# Usage:
#   sh tests/redaction-sweep.sh            # the jq hooks engine (needs jq)
#   sh tests/redaction-sweep.sh --port F   # also the OpenCode port's compiled
#                                          # redaction module F (needs node)
#   sh tests/redaction-sweep.sh --show N   # print N surviving inputs per engine
set -eu

# Pinned leak counts. Lower them when a fix lands; never raise them to make CI pass.
BASELINE_JQ=162
BASELINE_PORT=82

ROOT=$(cd "$(dirname "$0")/.." && pwd)
PORT=""
SHOW=0
while [ $# -gt 0 ]; do
  case "$1" in
    --port) PORT=$2; shift 2 ;;
    --show) SHOW=$2; shift 2 ;;
    *) echo "redaction-sweep: unknown argument $1" >&2; exit 2 ;;
  esac
done

command -v jq >/dev/null 2>&1 || { echo "redaction-sweep: jq is required" >&2; exit 2; }

tmp=$(mktemp -d 2>/dev/null || mktemp -d -t tlsweep)
trap 'rm -rf "$tmp"' EXIT INT TERM

# The corpus is generated by jq so the script needs nothing else. Secret-shaped values
# are assembled from pieces at run time, so this file holds no credential-shaped literal
# (tests/run.sh fails on one). Every value carries the marker MARK.
jq -nc '
  def mark: "zzSWEEP" + "MARKzz";
  def jwt: "ey" + "JhbGciOiJIUzI1NiJ9" + "." + "ey" + "JzdWIiOiJ4In0" + "." + mark;
  ["", "echo ", "--", "-H \"Authorization: ", "export ", "é", "ü"] as $pre
  | ["token", "secret", "password", "passwd", "api_key", "access-key", "credential",
     "auth", "authorization", "client_id", "bearer", "basic", "TOKEN", "Bearer", "Basic",
     "mytoken123", "DB_PASSWORD"] as $kw
  | ["token", "password", "auth", "bearer", "basic", "TOKEN", "mytoken123", "secret"] as $kw2
  | ["token", "secret", "password", "auth", "basic"] as $kw3
  | [": ", "=", " is ", " ", ":", " = "] as $sep
  | [": ", "=", " ", " is "] as $sep2
  | [mark, "\"" + mark + "\"", mark + "==", mark + "=", jwt, "mytoken" + mark,
     mark + ":x", "\"" + mark + " two\""] as $val
  | ["", " ok", "\"", " --verbose"] as $suf
  | ( ($pre[] as $p | $kw[] as $k | $sep[] as $s | $val[] as $v | $suf[] as $x
        | $p + $k + $s + $v + $x),
      ($pre[0:4][] as $p | $kw2[] as $k1 | $kw2[] as $k2 | $sep2[] as $s1 | $sep2[] as $s2
        | $val[0:3][] as $v | $p + $k1 + $s1 + $k2 + $s2 + $v),
      ($pre[0:2][] as $p | $kw3[] as $k1 | $kw3[] as $k2 | $kw3[] as $k3
        | $sep2[0:3][] as $s1 | $sep2[0:3][] as $s2 | $sep2[0:3][] as $s3
        | $p + $k1 + $s1 + $k2 + $s2 + $k3 + $s3 + mark + " ok") )
' > "$tmp/corpus.jsonl"
total=$(wc -l < "$tmp/corpus.jsonl" | tr -d ' ')

defs=$(sh -c ". \"$ROOT/hooks/_lib.sh\" && tl_jq_redact_defs")
jq -R -r "$defs fromjson | redact | tojson" "$tmp/corpus.jsonl" > "$tmp/jq.out"

status=0
# A broken engine must fail, not read as "0 leaks": every output line has to be a JSON
# string, one per corpus line. An engine that returns nothing, null, undefined or a
# Promise would otherwise count as leaking nothing.
check_shape() { # engine outfile
  if [ "$(wc -l < "$2" | tr -d ' ')" -ne "$total" ] || grep -qv '^"' "$2"; then
    echo "redaction-sweep: $1 returned malformed output (expected $total JSON strings)" >&2
    exit 2
  fi
}
report() { # engine outfile baseline
  leaks=$(paste "$tmp/corpus.jsonl" "$2" | grep -c 'zzSWEEPMARKzz[^	]*	.*zzSWEEPMARKzz' || true)
  echo "redaction-sweep: $1: $leaks of $total inputs leak the seeded marker (baseline $3)"
  if [ "$SHOW" -gt 0 ]; then
    paste "$tmp/corpus.jsonl" "$2" | grep 'zzSWEEPMARKzz[^	]*	.*zzSWEEPMARKzz' | head -n "$SHOW" | sed 's/^/  /'
  fi
  if [ "$leaks" -gt "$3" ]; then
    echo "redaction-sweep: $1 leaks more than its baseline - a regression (run with --show 20)" >&2
    status=1
  elif [ "$leaks" -lt "$3" ]; then
    echo "redaction-sweep: $1 leaks less than its baseline - lower BASELINE_$(echo "$1" | tr '[:lower:]' '[:upper:]') to $leaks"
  fi
}
check_shape jq "$tmp/jq.out"
report jq "$tmp/jq.out" "$BASELINE_JQ"

if [ -n "$PORT" ]; then
  command -v node >/dev/null 2>&1 || { echo "redaction-sweep: node is required for --port" >&2; exit 2; }
  node -e '
    const fs = require("fs");
    import(require("path").resolve(process.argv[1])).then((m) => {
      const out = fs.readFileSync(process.argv[2], "utf8").trim().split("\n")
        .map((l) => JSON.stringify(m.redact(JSON.parse(l))));
      fs.writeFileSync(process.argv[3], out.join("\n") + "\n");
    });
  ' "$PORT" "$tmp/corpus.jsonl" "$tmp/port.out"
  check_shape port "$tmp/port.out"
  report port "$tmp/port.out" "$BASELINE_PORT"
fi

exit "$status"
